import { z } from "zod";

/**
 * 공통 검증 라이브러리
 * 프론트엔드-백엔드 검증 규칙 일치를 보장합니다.
 *
 * CLAUDE.md 가이드라인에 따라 구현됨
 */

// ============================================
// Zod 스키마 (백엔드용)
// ============================================

export const ValidationSchemas = {
  // 일반회원 비밀번호 (숫자 4자리)
  userPassword: z
    .string()
    .regex(
      /^\d{4}$/,
      "비밀번호는 숫자 4자리로 입력해주세요."
    ),

  // 관리자 비밀번호 (최소 8자)
  adminPassword: z
    .string()
    .min(8, "비밀번호는 최소 8자 이상이어야 합니다."),

  // 이메일
  email: z
    .string()
    .email("올바른 이메일 형식이 아닙니다.")
    .toLowerCase()
    .trim(),

  // 전화번호 (01로 시작, 하이픈 선택)
  phone: z
    .string()
    .regex(
      /^01[0-9]-?[0-9]{3,4}-?[0-9]{4}$/,
      "올바른 전화번호 형식이 아닙니다. (예: 010-1234-5678)"
    ),

  // 이름 (한글/영문 2-50자)
  name: z
    .string()
    .min(2, "이름은 최소 2자 이상이어야 합니다.")
    .max(50, "이름은 최대 50자까지 입력 가능합니다.")
    .regex(
      /^[가-힣a-zA-Z\s]+$/,
      "이름은 한글 또는 영문만 입력 가능합니다."
    ),

  // Cohort ID (CUID 형식)
  cohortId: z.string().cuid("유효하지 않은 기수 ID입니다."),
};

// ============================================
// 정규식 (프론트엔드용)
// ============================================

export const ValidationRegex = {
  // 일반회원 비밀번호 (숫자 4자리)
  userPassword: /^\d{4}$/,

  // 이메일
  email: /^[^\s@]+@[^\s@]+\.[^\s@]+$/,

  // 전화번호 (01로 시작, 하이픈 선택)
  phone: /^01[0-9]-?[0-9]{3,4}-?[0-9]{4}$/,

  // 이름 (한글/영문)
  name: /^[가-힣a-zA-Z\s]+$/,
};

